export const photoText = (lang: string) => PHOTO_TRANSLATIONS[lang] ?? en;
// null means untouched default; even an empty user draft must be preserved.
export const photoCaption = (draft: string | null, lang: string) => draft ?? photoText(lang).defaultCaption;
export function photoError(error: unknown, lang: string) {
  const code = error instanceof Error ? error.message : '';
  const copy = photoText(lang);
  if (code === 'PHOTO_NOT_FOUND') return copy.fileMissing;
  if (code === 'PHOTO_TOO_LARGE') return copy.tooLarge;
  return copy.tryAgain;
}
